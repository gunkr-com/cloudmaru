import { fireEvent, screen, waitFor } from "@testing-library/react";
import userEvent from "@testing-library/user-event";
import { afterEach, beforeEach, expect, it, vi } from "vitest";
import { act } from "@testing-library/react";
import { I18nProvider } from "@/i18n/provider";
import { renderWithI18n as render } from "@/test/render-with-i18n";
import { ExtensionForm } from "./extension-form";
import { extension } from "@/lib/completion/fixtures.test-data";
import { loadExtensionSupportCatalog } from "@/lib/catalog/extension-support";
const router = vi.hoisted(() => ({ push: vi.fn() }));
vi.mock("next/navigation", () => ({ useRouter: () => router }));
const input = extension.input;
const props = { workspaceId: input.workspaceId, defaultRegion: input.region, regions: loadExtensionSupportCatalog().regions, scans: [{ id: input.sourceScanId, collectedAt: extension.sourceScan.collectedAt, source: "import" as const }] };
beforeEach(() => { vi.stubGlobal("fetch", vi.fn()); router.push.mockReset(); });
afterEach(() => vi.useRealTimers());
it.each(["en", "ko"] as const)("labels, validates and focuses source then requirements in %s", locale => {
  render(<ExtensionForm {...props} />, { locale });
  const scan = screen.getAllByRole("combobox")[0];
  fireEvent.submit(scan.closest("form")!);
  expect(scan).toHaveFocus(); expect(scan).toHaveAttribute("aria-invalid", "true");
  fireEvent.change(scan, { target: { value: input.sourceScanId } });
  expect(scan).toHaveAttribute("aria-invalid", "false");
  fireEvent.submit(scan.closest("form")!);
  expect(screen.getAllByRole("textbox")[0]).toHaveFocus();
  expect(screen.getAllByRole("textbox")[0]).toHaveAccessibleDescription();
  expect(fetch).not.toHaveBeenCalled();
});
it("submits entire input with keyboard shortcut, pins source/owner, and prevents duplicate pending requests", async () => {
  let resolve!: (r: Response) => void;
  vi.mocked(fetch).mockReturnValue(new Promise(r => { resolve = r; }));
  render(<ExtensionForm {...props} initialInput={{ ...input, description: "가".repeat(2000) }} sourceExtensionId={extension.id} />, { locale: "en" });
  const description = screen.getAllByRole("textbox")[0];
  fireEvent.keyDown(description, { key: "Enter", ctrlKey: true });
  fireEvent.submit(description.closest("form")!);
  expect(fetch).toHaveBeenCalledTimes(1);
  expect(JSON.parse(vi.mocked(fetch).mock.calls[0][1]!.body as string)).toEqual({ ...input, description: "가".repeat(2000), sourceExtensionId: extension.id });
  expect(screen.getByRole("status")).toHaveTextContent("Sending");
  expect(screen.getByRole("button", { name: "Run extension analysis" })).toBeDisabled();
  resolve(Response.json({ id: extension.id }, { status: 202 }));
  await waitFor(() => expect(router.push).toHaveBeenCalledWith(`/extensions/${extension.id}`));
  fireEvent.submit(description.closest("form")!);
  expect(fetch).toHaveBeenCalledTimes(1);
});
it.each(["workspace-changed", "invalid-source", "claude-unavailable", "pricing_unavailable", "internal"])("retains input and maps %s without server details", async code => {
  vi.mocked(fetch).mockResolvedValue(Response.json({ code, workspaceId: "attacker", detail: "SECRET" }, { status: 409 }));
  render(<ExtensionForm {...props} initialInput={input} />, { locale: "en" });
  fireEvent.click(screen.getByRole("button", { name: "Run extension analysis" }));
  await waitFor(() => expect(screen.getAllByRole("alert").length).toBeGreaterThan(0));
  expect(screen.getAllByRole("textbox")[0]).toHaveValue(input.description);
  expect(screen.getAllByRole("combobox")[0]).toHaveValue(input.sourceScanId);
  expect(screen.queryByText("SECRET")).not.toBeInTheDocument();
  if (code === "pricing_unavailable") expect(screen.getByText(/npm run prices:sync/)).toBeInTheDocument();
  if (code === "claude-unavailable") expect(screen.getByRole("link", { name: "Configure Claude key" })).toHaveAttribute("href", `/workspaces/${input.workspaceId}/claude`);
});
it("keeps a missing chosen scan visible and never substitutes a newly available scan", () => {
  const view = render(<ExtensionForm {...props} initialInput={input} />, { locale: "en" });
  view.rerender(<ExtensionForm {...props} scans={[{ ...props.scans[0], id: extension.id }]} initialInput={input} />);
  expect(screen.getAllByRole("combobox")[0]).toHaveValue(input.sourceScanId);
  fireEvent.click(screen.getByRole("button", { name: "Run extension analysis" }));
  expect(fetch).not.toHaveBeenCalled(); expect(screen.getAllByRole("alert").length).toBeGreaterThan(0);
});
it("supports keyboard choices and immediate field-error clearing", async () => {
  const user = userEvent.setup();
  render(<ExtensionForm {...props} initialInput={{ ...input, description: "short" }} />, { locale: "en" });
  fireEvent.click(screen.getByRole("button", { name: "Run extension analysis" }));
  const description = screen.getAllByRole("textbox")[0]; expect(description).toHaveFocus();
  await user.clear(description); await user.type(description, "Complete requirements");
  expect(description).toHaveAttribute("aria-invalid", "false");
  await user.tab(); expect(screen.getByLabelText("Expected users")).toHaveFocus();
  await user.selectOptions(screen.getByLabelText("Expected users"), "under-10k");
  expect(screen.getByLabelText("Expected users")).toHaveValue("under-10k");
});
it("aborts a request on unmount and ignores its late completion", async () => {
  let resolve!: (r: Response) => void;
  vi.mocked(fetch).mockReturnValue(new Promise(r => { resolve = r; }));
  const view = render(<ExtensionForm {...props} initialInput={input} />, { locale: "en" });
  fireEvent.click(screen.getByRole("button", { name: "Run extension analysis" }));
  const signal = vi.mocked(fetch).mock.calls[0][1]!.signal!;
  view.unmount(); expect(signal.aborted).toBe(true);
  resolve(Response.json({ id: extension.id }, { status: 202 }));
  await Promise.resolve(); await Promise.resolve(); expect(router.push).not.toHaveBeenCalled();
});
it("preserves typed input through locale changes and rejects a new props owner without rewriting it", () => {
  const view = render(<I18nProvider locale="en"><ExtensionForm {...props} initialInput={input} /></I18nProvider>);
  fireEvent.change(screen.getAllByRole("textbox")[0], { target: { value: "Unsaved extra requirements" } });
  view.rerender(<I18nProvider locale="ko"><ExtensionForm {...props} initialInput={input} workspaceId={extension.id} /></I18nProvider>);
  expect(screen.getAllByRole("textbox")[0]).toHaveValue("Unsaved extra requirements");
  expect(screen.getAllByRole("combobox")[0]).toHaveValue(input.sourceScanId);
  fireEvent.click(screen.getByRole("button")); expect(fetch).not.toHaveBeenCalled();
  expect(screen.getByRole("alert")).toHaveTextContent("워크스페이스");
});
it("focuses an editable field after a failed reanalysis request and permits retry", async () => {
  vi.mocked(fetch).mockRejectedValueOnce(Error("SECRET"));
  render(<ExtensionForm {...props} initialInput={input} sourceExtensionId={extension.id} />, { locale: "en" });
  const button = screen.getByRole("button"); button.focus(); fireEvent.click(button);
  await waitFor(() => expect(screen.getAllByRole("textbox")[0]).toHaveFocus());
  expect(screen.getByRole("alert")).not.toHaveTextContent("SECRET"); expect(button).toBeEnabled();
});
it("bounds submission, releases pending after timeout, and ignores late completion during the next request", async () => {
  vi.useFakeTimers();
  let first!: (r: Response) => void;
  vi.mocked(fetch).mockReturnValueOnce(new Promise(r => { first = r; })).mockReturnValueOnce(new Promise(() => {}));
  const view = render(<ExtensionForm {...props} initialInput={input} />, { locale: "en" });
  fireEvent.click(screen.getByRole("button"));
  await act(async () => { await vi.advanceTimersByTimeAsync(20_000); });
  expect(screen.getByRole("alert")).toHaveTextContent("in time");
  expect(screen.getByRole("button")).toBeEnabled();
  fireEvent.click(screen.getByRole("button")); expect(fetch).toHaveBeenCalledTimes(2);
  await act(async () => { first(Response.json({ id: extension.id }, { status: 202 })); });
  expect(router.push).not.toHaveBeenCalled();
  expect(screen.getByRole("button")).toBeDisabled();
  const signal = vi.mocked(fetch).mock.calls[1][1]!.signal!;
  view.unmount(); expect(signal.aborted).toBe(true);
  await act(async () => { await vi.advanceTimersByTimeAsync(30_000); });
  expect(fetch).toHaveBeenCalledTimes(2); expect(router.push).not.toHaveBeenCalled();
});
