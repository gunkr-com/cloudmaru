import { screen, within } from "@testing-library/react";
import { expect, it, vi } from "vitest";
const mocks = vi.hoisted(() => ({ listWorkspaces: vi.fn(), getCurrentWorkspace: vi.fn(), selectWorkspace: vi.fn(), getWorkspaceAzureSettings: vi.fn(), listLatestScanTimes: vi.fn() }));
vi.mock("@/services/db/workspace-azure", () => mocks);
vi.mock("@/services/db/scans", () => mocks);
vi.mock("@/services/db/workspaces", () => mocks);
vi.mock("@/services/current-workspace", () => mocks);
vi.mock("../workspace-actions", () => mocks);
vi.mock("./actions", () => ({ createWorkspaceAction: vi.fn(), updateWorkspaceAction: vi.fn() }));
vi.mock("@/components/workspace/workspace-form", () => ({ WorkspaceForm: ({ workspace }: { workspace?: { name: string } }) => <output>{workspace ? `수정: ${workspace.name}` : "만들기 폼"}</output> }));
import Page from "./page";
import { renderWithI18n } from "@/test/render-with-i18n";
it("lists region labels and dates, marks the current workspace and offers selection and editing", async () => {
  const base = { companyName: "Acme", defaultRegion: "canadacentral", createdAt: "2026-11-05T11:00:00.000Z" };
  mocks.getCurrentWorkspace.mockResolvedValue({ id: "first" });
  mocks.listWorkspaces.mockResolvedValue([{ ...base, id: "first", name: "First" }, { ...base, id: "second", name: "Second", defaultRegion: "canadacentral" }]);
  mocks.getWorkspaceAzureSettings.mockImplementation(async id => id === "first" ? { connection: {}, subscriptionIds: ["fake-subscription"] } : { connection: null, subscriptionIds: [] });
  mocks.listLatestScanTimes.mockResolvedValue({ first: "2026-11-06T12:05:00.000Z" });
  renderWithI18n(await Page(), { locale: "en" });
  expect(screen.getByRole("heading", { level: 1 })).toHaveTextContent("Workspaces");
  const rows = screen.getAllByRole("row");
  expect(within(rows[1]).getByRole("link", { name: "Claude API key: First" })).toHaveAttribute("href", "/workspaces/first/claude");
  expect(within(rows[1]).getByText("Current")).toBeInTheDocument();
  expect(within(rows[1]).queryByRole("button", { name: "Select" })).toBeNull();
  expect(within(rows[2]).getByRole("button", { name: "Select" })).toBeInTheDocument();
  expect(within(rows[2]).getByText("Canada Central")).toBeInTheDocument();
  expect(within(rows[1]).getByText("2026-11-05")).toBeInTheDocument();
  expect(screen.getAllByText("Edit")).toHaveLength(2);
  expect(screen.getByText("수정: First")).toBeInTheDocument();
  expect(screen.getByText("만들기 폼")).toBeInTheDocument();
  expect(within(rows[1]).getByText("Connected · 1 subscription")).toBeInTheDocument();
  expect(within(rows[2]).getByText("Not connected")).toBeInTheDocument();
  expect(within(rows[1]).getByRole("link", { name: "Edit connection: First" })).toHaveAttribute("href", "/workspaces/first/connection");
  expect(within(rows[2]).getByRole("link", { name: "Set up connection: Second" })).toHaveAttribute("href", "/workspaces/second/connection");
  const { formatDateTime } = await import("@/i18n/format");
  expect(within(rows[1]).getByText(formatDateTime("2026-11-06T12:05:00.000Z", "en"))).toBeInTheDocument();
  expect(within(rows[2]).getByText("—")).toBeInTheDocument();
  expect(mocks.listLatestScanTimes).toHaveBeenCalledTimes(1);
  expect(mocks.getWorkspaceAzureSettings).toHaveBeenCalledTimes(2);
  expect(screen.getByRole("table").parentElement).toHaveClass("overflow-x-auto");
  // sr-only spans in cells are absolutely positioned; without a positioned wrapper they widen the page at 375px.
  expect(screen.getByRole("table").parentElement).toHaveClass("relative");
  expect(screen.getByRole("table").parentElement).toHaveAttribute("tabindex", "0");
  expect(screen.getByRole("table").parentElement).toHaveAccessibleName("Workspaces");
});
